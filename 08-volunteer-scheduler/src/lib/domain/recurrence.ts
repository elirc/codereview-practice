import {
	addDays,
	civilDate,
	daysInMonth,
	fromDayNumber,
	parseCivilDate,
	toDayNumber,
	weekdayIndex,
	type CivilDate
} from './dates';

export const WEEKDAYS = ['MO', 'TU', 'WE', 'TH', 'FR', 'SA', 'SU'] as const;
export type Weekday = (typeof WEEKDAYS)[number];
export type Frequency = 'DAILY' | 'WEEKLY' | 'MONTHLY';

/** Upper bound on candidate dates examined by a single `occurrences` call. */
export const MAX_CANDIDATES = 1000;

export interface RecurrenceRule {
	freq: Frequency;
	interval: number;
	/** WEEKLY only. */
	byWeekday: readonly Weekday[] | null;
	/** MONTHLY only; -1 is the last day of the month. */
	byMonthDay: number | null;
	dtstart: CivilDate;
	/** Inclusive. */
	until: CivilDate | null;
	count: number | null;
}

export interface OccurrenceOptions {
	/** Dates to leave out of the result, such as cancelled occurrences. */
	skip?: ReadonlySet<CivilDate>;
}

/** Candidate dates in ascending order; `null` marks a month without the requested day. */
type Walk = Generator<CivilDate | null, void, undefined>;

function* walkDaily(rule: RecurrenceRule, from: CivilDate): Walk {
	const start = toDayNumber(rule.dtstart);
	const offset = toDayNumber(from) - start;
	let step = offset > 0 ? Math.ceil(offset / rule.interval) : 0;
	for (;; step++) yield fromDayNumber(start + step * rule.interval);
}

function* walkWeekly(rule: RecurrenceRule, from: CivilDate): Walk {
	const days = [...new Set((rule.byWeekday ?? []).map((day) => WEEKDAYS.indexOf(day)))].sort(
		(a, b) => a - b
	);
	if (days.length === 0) return;
	const baseMonday = toDayNumber(rule.dtstart) - weekdayIndex(rule.dtstart);
	const fromMonday = toDayNumber(from) - weekdayIndex(from);
	let week = Math.max(0, Math.floor((fromMonday - baseMonday) / 7));
	week -= week % rule.interval;
	for (;; week += rule.interval) {
		for (const day of days) yield fromDayNumber(baseMonday + week * 7 + day);
	}
}

function* walkMonthly(rule: RecurrenceRule, from: CivilDate): Walk {
	const monthDay = rule.byMonthDay;
	if (monthDay === null) return;
	const start = parseCivilDate(rule.dtstart);
	const target = parseCivilDate(from);
	let months = Math.max(0, (target.year - start.year) * 12 + (target.month - start.month));
	months -= months % rule.interval;
	for (;; months += rule.interval) {
		const index = start.month - 1 + months;
		const year = start.year + Math.floor(index / 12);
		const month = (index % 12) + 1;
		const length = daysInMonth(year, month);
		const day = monthDay === -1 ? length : monthDay;
		yield day <= length ? civilDate(year, month, day) : null;
	}
}

function walk(rule: RecurrenceRule, from: CivilDate): Walk {
	switch (rule.freq) {
		case 'DAILY':
			return walkDaily(rule, from);
		case 'WEEKLY':
			return walkWeekly(rule, from);
		case 'MONTHLY':
			return walkMonthly(rule, from);
	}
}

/**
 * Dates generated by `rule` that fall within the inclusive range
 * `[rangeStart, rangeEnd]`, without the dates in `options.skip`.
 */
export function occurrences(
	rule: RecurrenceRule,
	rangeStart: CivilDate,
	rangeEnd: CivilDate,
	options: OccurrenceOptions = {}
): CivilDate[] {
	const { skip } = options;
	const last = rule.until !== null && rule.until < rangeEnd ? rule.until : rangeEnd;
	if (last < rangeStart || last < rule.dtstart) return [];
	// A count is measured from dtstart, so only uncounted rules can start at the range.
	const from = rule.count === null && rangeStart > rule.dtstart ? rangeStart : rule.dtstart;

	const result: CivilDate[] = [];
	let examined = 0;
	let generated = 0;
	for (const candidate of walk(rule, from)) {
		examined += 1;
		if (examined > MAX_CANDIDATES) break;
		if (candidate === null || candidate < rule.dtstart || skip?.has(candidate)) continue;
		if (candidate > last) break;
		generated += 1;
		if (candidate >= rangeStart) result.push(candidate);
		if (rule.count !== null && generated >= rule.count) break;
	}
	return result;
}

/** The first `limit` occurrences on or after `from`, for previews. */
export function nextOccurrences(rule: RecurrenceRule, from: CivilDate, limit: number): CivilDate[] {
	return occurrences(rule, from, addDays(from, 3660)).slice(0, limit);
}

export function isOccurrence(rule: RecurrenceRule, date: CivilDate): boolean {
	return occurrences(rule, date, date).length === 1;
}

export function sameRule(a: RecurrenceRule, b: RecurrenceRule): boolean {
	const weekdays = (rule: RecurrenceRule) => [...(rule.byWeekday ?? [])].sort().join(',');
	return (
		a.freq === b.freq &&
		a.interval === b.interval &&
		weekdays(a) === weekdays(b) &&
		a.byMonthDay === b.byMonthDay &&
		a.dtstart === b.dtstart &&
		a.until === b.until &&
		a.count === b.count
	);
}
